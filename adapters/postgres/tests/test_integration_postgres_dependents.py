# The objects of the schemas in %(schemas)s as `dependents()` names them, minus the
# seed (%(s)s.seed) and what is part of it: its own constraints, policies, rules,
# defaults, triggers, columns and partitions.
_OBJECTS = """
SELECT CASE c.relkind WHEN 'v' THEN 'view' WHEN 'm' THEN 'materialized_view' ELSE 'table' END,
       n.nspname, c.relname
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = ANY(%(schemas)s) AND c.relkind IN ('r', 'p', 'f', 'v', 'm') AND NOT c.relispartition
  AND NOT (n.nspname = %(s)s AND c.relname = 'seed')
UNION
SELECT CASE p.prokind WHEN 'p' THEN 'procedure' ELSE 'function' END, n.nspname,
       p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')'
FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname = ANY(%(schemas)s)
UNION
SELECT 'constraint', n.nspname, k.conname || ' on ' || c.relname
FROM pg_constraint k
JOIN pg_class c ON c.oid = k.conrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = ANY(%(schemas)s) AND k.conparentid = 0
  AND NOT (n.nspname = %(s)s AND c.relname = 'seed')
UNION
SELECT 'policy', n.nspname, p.polname || ' on ' || c.relname
FROM pg_policy p
JOIN pg_class c ON c.oid = p.polrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = ANY(%(schemas)s) AND NOT (n.nspname = %(s)s AND c.relname = 'seed')
UNION
SELECT 'other', '', pg_describe_object('pg_attrdef'::regclass, d.oid, 0)
FROM pg_attrdef d
JOIN pg_class c ON c.oid = d.adrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
JOIN pg_attribute a ON a.attrelid = d.adrelid AND a.attnum = d.adnum
WHERE n.nspname = ANY(%(schemas)s) AND a.attgenerated = '' AND NOT (n.nspname = %(s)s AND c.relname = 'seed')
UNION
SELECT 'other', '', pg_describe_object('pg_type'::regclass, ty.oid, 0)
FROM pg_type ty JOIN pg_namespace n ON n.oid = ty.typnamespace
WHERE n.nspname = ANY(%(schemas)s) AND ty.typtype = 'd'
UNION
SELECT 'other', '', pg_describe_object('pg_trigger'::regclass, g.oid, 0)
FROM pg_trigger g
JOIN pg_class c ON c.oid = g.tgrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = ANY(%(schemas)s) AND NOT g.tgisinternal AND NOT (n.nspname = %(s)s AND c.relname = 'seed')
"""

# A column a cascade drops leaves its table (or composite type) in place, so a
# dropped column is read as the change of its table (or type).
_COLUMNS = """
SELECT CASE c.relkind WHEN 'c' THEN 'other' ELSE 'table' END, n.nspname, c.relname, a.attname
FROM pg_attribute a
JOIN pg_class c ON c.oid = a.attrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = ANY(%(schemas)s) AND c.relkind IN ('r', 'p', 'f', 'c')
  AND a.attnum > 0 AND NOT a.attisdropped
  AND NOT (n.nspname = %(s)s AND c.relname = 'seed')
"""


def _connect() -> Any:
    conn = psycopg2.connect(**PG)
    conn.autocommit = True
    return conn


def _query(sql: str, *params: Any) -> list[tuple[Any, ...]]:
    conn = _connect()
    try:
        with conn.cursor() as cur:
            cur.execute(sql, params)
            return list(cur.fetchall())
    finally:
        conn.close()


def _snapshot(cur: Any, params: dict[str, Any]) -> tuple[set[tuple[str, str, str]], set[tuple[str, str, str, str]]]:
    cur.execute(_OBJECTS, params)
    objects = set(cur.fetchall())
    cur.execute(_COLUMNS, params)
    return objects, set(cur.fetchall())


def _dropped_by_cascade(s: str, *others: str) -> set[tuple[str, str, str]]:
    """What ``DROP TABLE s.seed CASCADE`` removes or changes in schemas s and *others*, as (kind, schema, name); rolled back."""
    params = {"s": s, "schemas": [s, *others]}
    conn = psycopg2.connect(**PG)
    try:
        with conn.cursor() as cur:
            objects_before, columns_before = _snapshot(cur, params)
            cur.execute(f'DROP TABLE "{s}".seed CASCADE')
            objects_after, columns_after = _snapshot(cur, params)
        conn.rollback()
    finally:
        conn.close()
    changed_tables = {(kind, schema, table) for kind, schema, table, _ in columns_before - columns_after}
    return (objects_before - objects_after) | changed_tables


def _drop_everything(schemas: list[str], roles: list[str]) -> None:
    conn = _connect()
    try:
        with conn.cursor() as cur:
            for schema in schemas:
                with contextlib.suppress(psycopg2.Error):
                    cur.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
            for role in roles:
                with contextlib.suppress(psycopg2.Error):
                    cur.execute(f'DROP OWNED BY "{role}"')
                with contextlib.suppress(psycopg2.Error):
                    cur.execute(f'DROP ROLE IF EXISTS "{role}"')
    finally:
        conn.close()


